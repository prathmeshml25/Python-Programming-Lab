# 6.  Write a Python program to create a set, add a new element to it, remove an element using remove(), and discard an element using discard(). Given Input: fruits = {"apple", "banana", "cherry"} 

fruits = {"apple", "banana", "cherry"}

fruits.add("mango")
print(fruits)

fruits.remove("banana")
print(fruits)

fruits.discard("apple")
print(fruits)
